const tagClassMap = {
  "极高风险": "extreme",
  "高风险": "high",
  "中等风险": "medium"
};

function optionsFor(riskName) {
  return [
    [`${riskName}相关资料完整，能和合同、发票、资金、台账相互印证`, 0],
    [`${riskName}大体清楚，但少量资料需要补齐或复核`, 4],
    [`${riskName}经常事后补资料，差异较多`, 7],
    [`${riskName}长期说不清，和真实业务明显脱节`, 10]
  ];
}

function q(tag, title, desc, riskName, fix) {
  return {
    tag,
    tagClass: tagClassMap[tag],
    title,
    desc,
    riskName,
    fix,
    options: optionsFor(riskName)
  };
}

function buildIndustry(name, mark, description, actions, questions) {
  return {
    name,
    shortName: name,
    mark,
    description,
    actions,
    questions: questions.map((item) => q(...item))
  };
}

